/*
 * Role hierarchy: Gameplay > Combat > PaintMark
 * Primary responsibility: Defines the MaskRenderSO data asset used to configure runtime rules in the Inspector.
 * Execution boundary: Runtime (Assembly-CSharp)
 */

using UnityEngine;
using UnityEngine.Serialization;

[CreateAssetMenu(
    fileName = "MaskRender",
    menuName = "Game/Paint/Mask Render")]
public sealed class MaskRenderSO : DescriptionBaseSO
{
    public const string RuntimeMaskTextureProperty = "_MaskTex";

    [Header("Mask Identity")]
    [Tooltip("Gameplay mask channel stamped by this profile.")]
    [SerializeField] private PaintChannel _channel = PaintChannel.Vaccine;

    [Tooltip("Surface state represented by this profile for query/debug/UI.")]
    [SerializeField] private PaintSurfaceState _surfaceState = PaintSurfaceState.Vaccine;

    [Header("Overlay Visuals")]
    [Tooltip("Base material used by MaskRenderManager when this profile is assigned as a channel default.")]
    [SerializeField] private Material _baseMaterial;

    [Tooltip("Optional preview texture for inspector/UI. Runtime mask textures are generated by MaskRenderManager.")]
    [SerializeField] private Texture _previewTexture;

    [Header("Impact VFX")]
    [Tooltip("Particle prefab spawned when this mask stamp is accepted. Empty means no impact VFX.")]
    [FormerlySerializedAs("_paintBubbleParticlePrefab")]
    [SerializeField] private GameObject _impactVfxPrefab;

    [Header("Hostile Surface Contact")]
    [Tooltip("Non-stacking timed statuses refreshed while an opposing Shooter touches this paint. Friendly paint clears effects that opt into friendly removal.")]
    [SerializeField] private StatusEffectDefinitionSO[] _hostileContactEffects = System.Array.Empty<StatusEffectDefinitionSO>();

    public PaintChannel Channel => _channel;
    public PaintSurfaceState SurfaceState => _surfaceState;
    public PaintFaction Faction => PaintTypeUtility.ToFaction(_surfaceState);
    public PaintMarkFaction MarkFaction => PaintTypeUtility.ToMarkFaction(_surfaceState);
    public Material BaseMaterial => _baseMaterial;
    public Texture PreviewTexture => _previewTexture;
    public GameObject ImpactVfxPrefab => _impactVfxPrefab;
    public StatusEffectDefinitionSO[] HostileContactEffects => _hostileContactEffects;

    // Purpose: Attempts to validate runtime material and reports whether the request succeeded.
    public bool TryValidateRuntimeMaterial(out string error)
    {
        if (_baseMaterial == null)
        {
            error = $"[{nameof(MaskRenderSO)}] Base Material is missing: {name}";
            return false;
        }

        if (!_baseMaterial.HasProperty(RuntimeMaskTextureProperty))
        {
            error =
                $"[{nameof(MaskRenderSO)}] Base Material must use a mask shader with " +
                $"'{RuntimeMaskTextureProperty}'. maskRender={name}, material={_baseMaterial.name}";
            return false;
        }

        error = null;
        return true;
    }

#if UNITY_EDITOR
    // Purpose: Normalizes Inspector-authored data after it changes in the Editor.
    private void OnValidate()
    {
        if (!TryValidateRuntimeMaterial(out string error))
            Debug.LogError(error, this);
    }
#endif
}
